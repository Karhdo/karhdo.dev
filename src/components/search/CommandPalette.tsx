/**
 * ⌘K command palette (task 23): a plain React component mounted by `mount-palette.tsx`, never an
 * Astro island. Mockup `.cmdk` dialog.
 *
 * - Dialog: a native modal `<dialog>` (top layer, inert page behind it, Esc via `cancel`), so no
 *   extra Radix dependency. Focus returns to the element that opened it. Opened/closed through the
 *   `cmdk:open` / `cmdk:toggle` window events from CommandPaletteLoader.astro.
 * - List: `cmdk` with `shouldFilter={false}` (Pagefind ranks posts; pages/actions use `matchesQuery`).
 *   cmdk gives the input `role="combobox"` and the list `role="listbox"` with `aria-activedescendant`.
 * - Pagefind (`/pagefind/pagefind.js`, generated by `bun run build`) is imported on the first open.
 */
import { navigate } from 'astro:transitions/client';
import { Command } from 'cmdk';
import { type ReactNode, useCallback, useEffect, useLayoutEffect, useRef, useState } from 'react';
import { getTheme, resolveTheme, switchTheme, type ThemePref } from '~/lib/theme';
import {
  isExternal,
  isFile,
  MAX_RESULTS,
  matchesQuery,
  type PagefindFragment,
  type PaletteData,
  type PaletteLink,
  type PalettePost,
  toPalettePost,
} from './palette-data';

type PagefindResult = { id: string; data(): Promise<PagefindFragment> };
type Pagefind = {
  options(options: Record<string, unknown>): Promise<void>;
  init(): Promise<void> | void;
  debouncedSearch(term: string, options?: object, debounceMs?: number): Promise<{ results: PagefindResult[] } | null>;
};

type SearchState =
  | { status: 'idle' }
  | { status: 'loading'; query: string }
  | { status: 'done'; query: string; posts: PalettePost[] }
  | { status: 'unavailable' };

let pagefind: Promise<Pagefind> | undefined;

/** Loads and initialises Pagefind once per page life (the palette root is persisted across navigations). */
function loadPagefind(): Promise<Pagefind> {
  pagefind ??= (async () => {
    const path = '/pagefind/pagefind.js'; // a variable, so Vite leaves the runtime import alone
    const module = (await import(/* @vite-ignore */ path)) as Pagefind;
    await module.options({ excerptLength: 20 });
    await module.init();
    return module;
  })().catch((error: unknown) => {
    pagefind = undefined; // let the next open retry (e.g. a transient network error)
    throw error;
  });
  return pagefind;
}

